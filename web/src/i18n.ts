/** Localize a backend status/level token; unknown tokens fall back to the raw value. */
export function localizeStatus(t: TFunction, value?: string | boolean | null): string {
  const raw = String(value ?? "").trim()
  if (!raw) return "-"
  if (t("builds") !== "构建部署") return raw
  return STATUS_ZH[raw.toLowerCase()] ?? raw
}

export function getInitialLocale(): Locale {
  const stored = window.localStorage.getItem("lingshu-gate-console-locale")
  if (stored === "en-US" || stored === "zh-CN") return stored
  return "zh-CN"
}

export function saveLocale(locale: Locale) {
  window.localStorage.setItem("lingshu-gate-console-locale", locale)
}

export function translate(locale: Locale, key: MessageKey) {
  return messages[locale][key] || messages["zh-CN"][key] || key
}
